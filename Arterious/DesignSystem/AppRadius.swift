import SwiftUI

/// Centralized corner radius tokens for Arterious.
/// Apply consistently across cards, buttons, and chips to maintain visual coherence.
enum AppRadius {

    /// 8 pt — small elements like badges and chips.
    static let sm: CGFloat = 8

    /// 12 pt — compact cards or inner containers.
    static let md: CGFloat = 12

    /// 16 pt — standard metric cards.
    static let lg: CGFloat = 16

    /// 20 pt — prominent cards like CautionCard and status headers.
    static let xl: CGFloat = 20
}
